// Generates assets-manifest.md: an inventory of every brand, icon, diagram, illustration and social asset.
import fs from 'node:fs';
import path from 'node:path';

const pub = path.resolve('public');
const walk = (d) => fs.existsSync(d) ? fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)])) : [];
const kb = (f) => `${(fs.statSync(f).size / 1024).toFixed(1)} KB`;
const title = (f) => (f.endsWith('.svg') ? (/<title>([^<]+)<\/title>/.exec(fs.readFileSync(f, 'utf8'))?.[1] ?? '') : '');
const section = (heading, dir, note) => {
  const files = walk(path.join(pub, dir)).filter((f) => !path.basename(f).startsWith('.')).sort();
  if (!files.length) return '';
  return `## ${heading} (${files.length})\n\n${note ? note + '\n\n' : ''}| File | Size | Description |\n|---|---|---|\n${files.map((f) => `| \`/${path.relative(pub, f)}\` | ${kb(f)} | ${title(f).replace(/\|/g, '/')} |`).join('\n')}\n\n`;
};
const root = ['favicon.svg', 'favicon.ico', 'apple-touch-icon.png', 'site.webmanifest', 'robots.txt', '_headers', '_redirects'];
let md = `# Panoptes — asset manifest\n\nGenerated by \`node scripts/assets-manifest.mjs\`. All assets are original to this project. Logos, favicons and social images are generated by \`npm run assets\` (scripts/generate-assets.mjs) from vector geometry; wordmark glyphs are Space Grotesk (SIL OFL 1.1) converted to outlines.\n\n`;
md += `## Root files\n\n| File | Size |\n|---|---|\n${root.filter((f) => fs.existsSync(path.join(pub, f))).map((f) => `| \`/${f}\` | ${kb(path.join(pub, f))} |`).join('\n')}\n\n`;
md += section('Logos — master SVG', 'logos', 'Text converted to paths; no font dependency. PNG exports at 256/512/1024 px wide live in `/logos/png/`.').replace(/\| `\/logos\/png\/[^\n]+\n/g, '');
md += section('Logos — PNG exports', 'logos/png');
md += section('Favicons & app icons', 'icons', 'UI icons (`/icons/ui/`) are 24×24 stroke icons using `currentColor`, inlined at build time.');
md += section('Diagrams', 'diagrams', 'Theme-aware SVGs (CSS variables with light fallbacks) — see AUTHORING.md.');
md += section('Illustrations', 'illustrations');
md += section('Product screens', 'screenshots');
md += section('Social sharing images', 'social', '1200×630 Open Graph images (PNG used in meta tags; SVG masters alongside).');
md += section('Fonts', 'fonts', 'Self-hosted variable WOFF2, latin subset. Licensed under the SIL Open Font License 1.1 (licence files included).');
fs.writeFileSync('assets-manifest.md', md);
console.log('assets-manifest.md written');
